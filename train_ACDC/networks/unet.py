class CenterAnchoredNeighborRelationAdapter(nn.Module):
    """Explicit prev/next relation adapter anchored on the center x0 feature."""

    def __init__(self, feat_channels=16, relation_dim=8, eps=1e-6):
        super(CenterAnchoredNeighborRelationAdapter, self).__init__()
        self.feat_channels = feat_channels
        self.relation_dim = relation_dim
        self.eps = eps
        self.neighbor_adapter = nn.Sequential(
            nn.Conv2d(1, 8, kernel_size=3, padding=1),
            nn.LeakyReLU(),
            nn.Conv2d(8, feat_channels, kernel_size=3, padding=1),
            nn.LeakyReLU(),
        )
        self.query_proj = nn.Conv2d(feat_channels, relation_dim, kernel_size=1)
        self.key_proj = nn.Conv2d(feat_channels, relation_dim, kernel_size=1)
        self.value_proj = nn.Conv2d(feat_channels, feat_channels, kernel_size=1)
        self.out_proj = nn.Conv2d(feat_channels, feat_channels, kernel_size=1)
        nn.init.zeros_(self.out_proj.weight)
        nn.init.zeros_(self.out_proj.bias)
        self.last_stats = {}

    @staticmethod
    def _expand_validity(neighbor_validity, x_center):
        b, _, h, w = x_center.shape
        if neighbor_validity is None:
            return torch.ones((b, 2, h, w), dtype=x_center.dtype, device=x_center.device)
        valid = neighbor_validity.to(device=x_center.device, dtype=x_center.dtype)
        if valid.ndim == 2:
            valid = valid[:, :, None, None].expand(-1, -1, h, w)
        elif valid.ndim == 4:
            if valid.shape[-2:] != (h, w):
                valid = F.interpolate(valid, size=(h, w), mode="nearest")
        else:
            raise ValueError("neighbor_validity must be [B,2] or [B,2,H,W]")
        if valid.shape[1] != 2:
            raise ValueError("neighbor_validity channel dimension must be 2 (prev,next)")
        return valid.clamp(0.0, 1.0)

    def safe_masked_softmax(self, scores, valid):
        valid = valid.to(dtype=scores.dtype, device=scores.device)
        valid_bool = valid > 0
        masked_scores = scores.masked_fill(~valid_bool, -1e4)
        max_score = masked_scores.amax(dim=1, keepdim=True)
        weights = torch.exp(masked_scores - max_score) * valid
        denom = weights.sum(dim=1, keepdim=True)
        alpha = weights / torch.clamp(denom, min=self.eps)
        alpha = torch.where(denom > 0, alpha, torch.zeros_like(alpha))
        return alpha

    def forward(self, x_center, prev_img, next_img, neighbor_validity=None):
        valid = self._expand_validity(neighbor_validity, x_center)
        f_prev = self.neighbor_adapter(prev_img)
        f_next = self.neighbor_adapter(next_img)

        q = self.query_proj(x_center)
        k_prev = self.key_proj(f_prev)
        k_next = self.key_proj(f_next)
        v_prev = self.value_proj(f_prev)
        v_next = self.value_proj(f_next)

        score_prev = (q * k_prev).sum(dim=1, keepdim=True) / math.sqrt(float(self.relation_dim))
        score_next = (q * k_next).sum(dim=1, keepdim=True) / math.sqrt(float(self.relation_dim))
        scores = torch.cat([score_prev, score_next], dim=1)
        alpha = self.safe_masked_softmax(scores, valid)

        relation = alpha[:, 0:1] * v_prev + alpha[:, 1:2] * v_next
        residual = self.out_proj(relation)
        fused = x_center + residual

        with torch.no_grad():
            entropy = -(alpha * torch.log(torch.clamp(alpha, min=self.eps))).sum(dim=1).mean()
            self.last_stats = {
                "scores_shape": tuple(scores.shape),
                "alpha_shape": tuple(alpha.shape),
                "mean_alpha_prev": alpha[:, 0].mean().detach(),
                "mean_alpha_next": alpha[:, 1].mean().detach(),
                "std_alpha_prev": alpha[:, 0].std().detach(),
                "std_alpha_next": alpha[:, 1].std().detach(),
                "attention_entropy": entropy.detach(),
                "valid_prev_ratio": valid[:, 0].mean().detach(),
                "valid_next_ratio": valid[:, 1].mean().detach(),
                "prev_value_norm": v_prev.norm().detach(),
                "next_value_norm": v_next.norm().detach(),
                "relation_norm": relation.norm().detach(),
                "residual_norm": residual.norm().detach(),
            }
        return fused


